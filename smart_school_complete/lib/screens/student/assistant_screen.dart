import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../../models.dart';
import '../../services/assistant.dart';
import '../../services/helpers.dart';
import '../../services/session.dart';
import '../../theme.dart';
import '../../widgets/common.dart';

class AssistantScreen extends StatefulWidget {
  const AssistantScreen({super.key});
  @override
  State<AssistantScreen> createState() => _AssistantScreenState();
}

class _AssistantScreenState extends State<AssistantScreen> {
  late Future<AssistantReport> _f = _load();

  Future<AssistantReport> _load() {
    final s = context.read<SessionController>();
    return s.run(() async {
      final progress = asList(await s.db.rpc('my_progress'));
      AttSummary? att;
      try { att = AttSummary.fromJson(Map<String, dynamic>.from(await s.db.rpc('attendance_summary') as Map)); } catch (_) {}
      return buildAdvice(progress, att);
    });
  }

  Color _c(String st) => switch (st) { 'practice' => AppColors.coral, 'declining' => AppColors.amber, 'improving' => AppColors.mint, 'strong' => AppColors.mint, _ => AppColors.muted };
  String _label(String st) => switch (st) { 'practice' => 'Needs practice', 'declining' => 'Dropped', 'improving' => 'Improving', 'strong' => 'Strong', _ => 'Steady' };

  @override
  Widget build(BuildContext context) => Scaffold(
        appBar: AppBar(title: const Text('Study Assistant')),
        body: SafeArea(child: FutureBuilder<AssistantReport>(
          future: _f,
          builder: (c, snap) {
            if (snap.connectionState != ConnectionState.done) return const LoadingView();
            if (snap.hasError) return ErrorView(snap.error!, () => setState(() => _f = _load()));
            final r = snap.data!;
            if (r.subjects.isEmpty) return const EmptyView(Icons.psychology_outlined, 'Advice appears after your first published results.');
            return ListView(padding: const EdgeInsets.all(16), children: [
              if (r.overallChange != null) Card(child: ListTile(
                leading: Icon(r.overallChange! >= 0 ? Icons.trending_up : Icons.trending_down, color: r.overallChange! >= 0 ? AppColors.mint : AppColors.coral),
                title: Text(r.overallChange! >= 0 ? 'Up ${r.overallChange!.toStringAsFixed(1)} points since the last exam' : 'Down ${(-r.overallChange!).toStringAsFixed(1)} points since the last exam'),
                subtitle: const Text('Average across all subjects, latest vs previous examination'))),
              const SizedBox(height: 12),
              for (final s in r.subjects) Padding(padding: const EdgeInsets.only(bottom: 10), child: Card(child: Padding(padding: const EdgeInsets.all(14), child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Row(children: [
                  Expanded(child: Text(s.subject, style: display(19))),
                  Text(pct(s.latest), style: TextStyle(fontWeight: FontWeight.w800, fontSize: 18, color: _c(s.status))),
                ]),
                const SizedBox(height: 2),
                Text('${_label(s.status)}${s.change == null ? '' : '  -  ${s.change! >= 0 ? '+' : ''}${s.change}'} vs previous', style: TextStyle(color: _c(s.status), fontSize: 12, fontWeight: FontWeight.w600)),
                const SizedBox(height: 8),
                Text(s.advice, style: const TextStyle(height: 1.4)),
              ])))),
              if (r.attendanceNotes.isNotEmpty) ...[
                Text('Attendance', style: display(19)),
                const SizedBox(height: 8),
                for (final t in r.attendanceNotes) Padding(padding: const EdgeInsets.only(bottom: 8), child: Card(child: ListTile(leading: const Icon(Icons.warning_amber_rounded, color: AppColors.amber), title: Text(t, style: const TextStyle(fontSize: 14))))),
              ],
              const SizedBox(height: 8),
              const Text('This advice is generated by simple rules from your verified marks and attendance. It cannot create, change or publish marks.', style: TextStyle(color: AppColors.muted, fontSize: 12)),
            ]);
          },
        )),
      );
}
